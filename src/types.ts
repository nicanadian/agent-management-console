// === Three-axis status ===
//
// The PRD separates agent claim / validator verdict / human decision (§5,
// UX principle #2). The prototype previously collapsed these into one
// `status` enum; they're now four explicit axes — one for queue lifecycle
// and three for the orthogonal verdicts. UI buckets are derived via
// `taskBucket()` below.

// Where does this task live in your queue right now?
export type LifecycleStatus =
  | 'inbox'      // captured, no agent
  | 'queued'     // assigned, not started
  | 'running'    // active run in progress
  | 'blocked'    // waiting on user input, missing creds, external dep
  | 'done'       // most recent run terminated; verdicts determine bucket
  | 'cancelled'  // user-killed before completion
  | 'archived';

// What did the latest run terminate with (if any)?
export type ClaimedStatus =
  | 'none'       // no run has terminated yet
  | 'succeeded'  // agent claims success
  | 'failed';    // agent reports its own failure

// What did the deterministic validator find on the latest run?
//
// `judged_ok` / `judged_concerns` are the LLM-as-judge band (Phase 9.3) —
// distinct from `verified` so a judge result alone never clears
// `unverified`. Use them for research / docs tasks where deterministic
// checks miss the meaningful failure modes.
export type ValidationStatus =
  | 'not_applicable'
  | 'pending'
  | 'verified'
  | 'partially_verified'
  | 'unverified'
  | 'failed'
  | 'judged_ok'
  | 'judged_concerns';

// What did the human decide?
export type ReviewStatus =
  | 'not_required'
  | 'pending'
  | 'accepted'
  | 'rejected'
  | 'needs_changes';

