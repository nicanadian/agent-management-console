// Phase 9.4 — Anthropic's prompt caching breaks single-`tokens` accounting.
// Splitting the fields out keeps cost reconciliation honest without
// pretending we know which tokens belong to which task.
export interface TokenUsage {
  input?: number | null;
  output?: number | null;
  cacheCreate?: number | null;
  cacheRead?: number | null;
}

export interface Artifact {
  name: string;
  type: 'file' | 'diff' | 'log' | 'report';
  preview?: string;
}

export interface Run {
  id: string;
  taskId: string;
  agentId: string;
  status: RunStatus;
  startedAt: string;
  endedAt?: string;
  runtime?: string;
  // `cost` is the legacy single-number USD field (kept for back-compat
  // with views that already render it). Phase 9.4 prefers `costUsd`
  // alongside `tokens` and `costSource` so the UI can mark task-level
  // cost as approximate when caching distorts attribution.
  cost?: number;
  costUsd?: number;
  costSource?: 'estimated' | 'billed';
  // Captured from claude's stream-json `system.init` event. `'none'` means
  // a subscription quota is paying — `costUsd` is then *notional* (what
  // those tokens would cost on the API). `'user' | 'project' | 'org'`
  // mean a real API key, and `costUsd` is actually billed money.
  apiKeySource?: 'none' | 'user' | 'project' | 'org' | string;
  tokens?: TokenUsage;
  agentSummary?: string;
  validationStatus?: ValidationStatus;
  validation?: ValidationCheck[];
  artifacts?: Artifact[];
  activity?: Activity[];
  // Live fields written by tools/claude-shim.mjs as the run progresses
  // (Phase 6.3) and the session id captured for --resume (Phase 6.4).
  sessionId?: string;
  resumedFromSessionId?: string;
  lastToolName?: string;
  toolCount?: number;
  currentActivity?: string;
  updatedAt?: string;
  // Set by the console-server's stale-run sweep (Phase 7.1) when a run
  // is marked 'unknown' because its daemon disappeared without writing
  // a terminal status. Values: 'no_heartbeat' for now; expand later.
  terminationReason?: string;
}

